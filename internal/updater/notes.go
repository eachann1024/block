package updater

import (
	"slices"
	"strings"
)

// LocalizedNotes holds user-facing release notes in a single language.
type LocalizedNotes struct {
	Highlights   string   `json:"highlights,omitempty"`
	New          []string `json:"new,omitempty"`
	Improvements []string `json:"improvements,omitempty"`
	Fixes        []string `json:"fixes,omitempty"`
	Other        []string `json:"other,omitempty"`
}

// TaggedBullet pairs a changelog item with the version tag that introduced it.
type TaggedBullet struct {
	Text    string `json:"text"`
	Version string `json:"version"`
}

// TaggedLocalizedNotes preserves originating version tags per bullet for cross-version grouped display.
type TaggedLocalizedNotes struct {
	Highlights   string         `json:"highlights,omitempty"`
	New          []TaggedBullet `json:"new,omitempty"`
	Improvements []TaggedBullet `json:"improvements,omitempty"`
	Fixes        []TaggedBullet `json:"fixes,omitempty"`
	Other        []TaggedBullet `json:"other,omitempty"`
}

// IsEmpty reports whether all sections are empty.
func (n LocalizedNotes) IsEmpty() bool {
	return strings.TrimSpace(n.Highlights) == "" &&
		len(n.New) == 0 &&
		len(n.Improvements) == 0 &&
		len(n.Fixes) == 0 &&
		len(n.Other) == 0
}

// IsEmpty reports whether all tagged sections are empty.
func (n TaggedLocalizedNotes) IsEmpty() bool {
	return strings.TrimSpace(n.Highlights) == "" &&
		len(n.New) == 0 &&
		len(n.Improvements) == 0 &&
		len(n.Fixes) == 0 &&
		len(n.Other) == 0
}

// ReleaseAsset describes one downloadable installer attached to a release.
type ReleaseAsset struct {
	Name        string `json:"name"`
	DownloadURL string `json:"browser_download_url"`
	Size        int64  `json:"size,omitempty"`
	SHA256      string `json:"sha256,omitempty"`
	Digest      string `json:"digest,omitempty"`
}

// EffectiveSHA256 returns the lowercase 64-character hex SHA-256 digest if present.
func (a ReleaseAsset) EffectiveSHA256() string {
	raw := strings.TrimSpace(a.SHA256)
	if raw == "" {
		raw = strings.TrimPrefix(strings.TrimSpace(a.Digest), "sha256:")
	}
	raw = strings.ToLower(strings.TrimSpace(raw))
	if len(raw) != 64 {
		return ""
	}
	for i := 0; i < len(raw); i++ {
		c := raw[i]
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return ""
		}
	}
	return raw
}

// ReleaseEntry represents one published version in updates/feed.json or GitHub Releases.
type ReleaseEntry struct {
	Version     string         `json:"version"`
	Tag         string         `json:"tag"`
	PublishedAt string         `json:"published_at,omitempty"`
	HTMLURL     string         `json:"html_url,omitempty"`
	Zh          LocalizedNotes `json:"zh"`
	En          LocalizedNotes `json:"en"`
	Assets      []ReleaseAsset `json:"assets,omitempty"`
}

// FeedDocument matches updates/feed.json generated by scripts/release/update-feed.mjs.
type FeedDocument struct {
	SchemaVersion int            `json:"schema_version"`
	Repo          string         `json:"repo"`
	UpdatedAt     string         `json:"updated_at"`
	LatestVersion string         `json:"latest_version"`
	LatestTag     string         `json:"latest_tag"`
	Releases      []ReleaseEntry `json:"releases"`
}

// AggregatedNotes holds cross-version merged and per-version bilingual changelogs.
type AggregatedNotes struct {
	FromVersion  string               `json:"from_version"`
	ToVersion    string               `json:"to_version"`
	VersionCount int                  `json:"version_count"`
	HasNewer     bool                 `json:"has_newer"`
	PublishedAt  string               `json:"published_at,omitempty"`
	MergedZh     LocalizedNotes       `json:"merged_zh"`
	MergedEn     LocalizedNotes       `json:"merged_en"`
	TaggedZh     TaggedLocalizedNotes `json:"tagged_zh"`
	TaggedEn     TaggedLocalizedNotes `json:"tagged_en"`
	Versions     []ReleaseEntry       `json:"versions"`
}

// ForLanguage returns the merged notes matching the active UI language.
func (a AggregatedNotes) ForLanguage(isEn bool) LocalizedNotes {
	if isEn {
		if !a.MergedEn.IsEmpty() {
			return a.MergedEn
		}
		return a.MergedZh
	}
	if !a.MergedZh.IsEmpty() {
		return a.MergedZh
	}
	return a.MergedEn
}

// TaggedForLanguage returns the version-tagged merged notes matching the requested language.
func (a AggregatedNotes) TaggedForLanguage(isEn bool) TaggedLocalizedNotes {
	if isEn {
		if !a.TaggedEn.IsEmpty() {
			return a.TaggedEn
		}
		return a.TaggedZh
	}
	if !a.TaggedZh.IsEmpty() {
		return a.TaggedZh
	}
	return a.TaggedEn
}

// VersionForLanguage returns one version's notes matching the active UI language.
func VersionForLanguage(entry ReleaseEntry, isEn bool) LocalizedNotes {
	if isEn {
		if !entry.En.IsEmpty() {
			return entry.En
		}
		return entry.Zh
	}
	if !entry.Zh.IsEmpty() {
		return entry.Zh
	}
	return entry.En
}

// ShortDate returns YYYY-MM-DD from an RFC3339 timestamp.
func ShortDate(iso string) string {
	trimmed := strings.TrimSpace(iso)
	if len(trimmed) >= 10 && trimmed[4] == '-' && trimmed[7] == '-' {
		return trimmed[:10]
	}
	return trimmed
}

func looksChinese(text string) bool {
	if strings.Contains(text, "## 中文") || strings.Contains(text, "本次更新重点") ||
		strings.Contains(text, "### 新功能") || strings.Contains(text, "### 改进") ||
		strings.Contains(text, "### 修复") || strings.Contains(text, "✨ 新功能") {
		return true
	}
	for _, r := range text {
		if r >= 0x4E00 && r <= 0x9FFF {
			return true
		}
	}
	return false
}

// ParseReleaseBody splits a bilingual GitHub Release Markdown body into Zh and En sections.
func ParseReleaseBody(raw string) (zh LocalizedNotes, en LocalizedNotes) {
	norm := strings.ReplaceAll(raw, "\r\n", "\n")
	norm = strings.TrimSpace(norm)
	if norm == "" {
		return LocalizedNotes{}, LocalizedNotes{}
	}

	var left, right string
	if idx := strings.Index(norm, "\n---\n"); idx >= 0 {
		left = strings.TrimSpace(norm[:idx])
		right = strings.TrimSpace(norm[idx+5:])
	} else if idx := strings.Index(norm, "\n---"); idx >= 0 {
		left = strings.TrimSpace(norm[:idx])
		right = strings.TrimSpace(norm[idx+4:])
	} else {
		parsed := parseSingleHalf(norm)
		return parsed, parsed
	}

	if right == "" {
		parsed := parseSingleHalf(left)
		return parsed, parsed
	}
	if looksChinese(right) && !looksChinese(left) {
		return parseSingleHalf(right), parseSingleHalf(left)
	}
	if looksChinese(left) && !looksChinese(right) {
		return parseSingleHalf(left), parseSingleHalf(right)
	}
	return parseSingleHalf(right), parseSingleHalf(left)
}

func parseSingleHalf(text string) LocalizedNotes {
	var out LocalizedNotes
	section := ""

	for _, rawLine := range strings.Split(text, "\n") {
		line := strings.TrimSpace(rawLine)
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "Website:") || strings.HasPrefix(line, "官网：") || strings.HasPrefix(line, "官网:") {
			section = "skip"
			continue
		}

		if (strings.HasPrefix(line, "🌈") || strings.Contains(line, "本次更新重点") || strings.Contains(line, "Highlights")) && out.Highlights == "" {
			hl := strings.TrimLeft(line, "🌈# ")
			for _, p := range []string{"本次更新重点：", "本次更新重点:", "Highlights:", "Highlights："} {
				hl = strings.TrimPrefix(hl, p)
			}
			out.Highlights = strings.TrimSpace(hl)
			continue
		}

		if strings.HasPrefix(line, "#") || strings.HasPrefix(line, "✨") || strings.HasPrefix(line, "🪐") || strings.HasPrefix(line, "🐛") {
			h := strings.TrimSpace(strings.TrimLeft(line, "#✨🪐🐛 "))
			hLower := strings.ToLower(h)
			switch {
			case hLower == "english" || h == "中文":
				continue
			case hLower == "download" || hLower == "install" || strings.Contains(h, "下载") || strings.Contains(h, "安装"):
				section = "skip"
			case hLower == "new" || strings.Contains(h, "新功能") || strings.HasPrefix(hLower, "new "):
				section = "new"
			case hLower == "improvements" || hLower == "improved" || strings.Contains(h, "改进") || strings.Contains(h, "优化"):
				section = "improvements"
			case hLower == "fixes" || hLower == "fixed" || strings.Contains(h, "修复"):
				section = "fixes"
			case hLower == "other" || strings.Contains(h, "其他"):
				section = "other"
			default:
				if strings.HasPrefix(line, "✨") {
					section = "new"
				} else if strings.HasPrefix(line, "🪐") {
					section = "improvements"
				} else if strings.HasPrefix(line, "🐛") {
					section = "fixes"
				}
			}
			continue
		}

		if section == "skip" {
			continue
		}

		var bullet string
		switch {
		case strings.HasPrefix(line, "- "):
			bullet = strings.TrimSpace(line[2:])
		case strings.HasPrefix(line, "* "):
			bullet = strings.TrimSpace(line[2:])
		case strings.HasPrefix(line, "• "):
			bullet = strings.TrimSpace(strings.TrimPrefix(line, "•"))
		}
		if bullet == "" {
			continue
		}
		bullet = strings.ReplaceAll(bullet, "**", "")
		switch section {
		case "new":
			out.New = appendUnique(out.New, bullet)
		case "improvements":
			out.Improvements = appendUnique(out.Improvements, bullet)
		case "fixes":
			out.Fixes = appendUnique(out.Fixes, bullet)
		case "other":
			out.Other = appendUnique(out.Other, bullet)
		default:
			out.Improvements = appendUnique(out.Improvements, bullet)
		}
	}
	return out
}

func appendUnique(dst []string, item string) []string {
	if item == "" || slices.Contains(dst, item) {
		return dst
	}
	return append(dst, item)
}

func appendUniqueTagged(dst []TaggedBullet, text, ver string) []TaggedBullet {
	if text == "" {
		return dst
	}
	for _, existing := range dst {
		if existing.Text == text {
			return dst
		}
	}
	return append(dst, TaggedBullet{Text: text, Version: ver})
}

func mergeLocalized(dst *LocalizedNotes, tagged *TaggedLocalizedNotes, src LocalizedNotes, verTag string) {
	if dst.Highlights == "" && src.Highlights != "" {
		dst.Highlights = src.Highlights
	}
	if tagged.Highlights == "" && src.Highlights != "" {
		tagged.Highlights = src.Highlights
	}
	for _, it := range src.New {
		dst.New = appendUnique(dst.New, it)
		tagged.New = appendUniqueTagged(tagged.New, it, verTag)
	}
	for _, it := range src.Improvements {
		dst.Improvements = appendUnique(dst.Improvements, it)
		tagged.Improvements = appendUniqueTagged(tagged.Improvements, it, verTag)
	}
	for _, it := range src.Fixes {
		dst.Fixes = appendUnique(dst.Fixes, it)
		tagged.Fixes = appendUniqueTagged(tagged.Fixes, it, verTag)
	}
	for _, it := range src.Other {
		dst.Other = appendUnique(dst.Other, it)
		tagged.Other = appendUniqueTagged(tagged.Other, it, verTag)
	}
}

// AggregateReleases computes cross-version merged and per-version changelogs.
func AggregateReleases(releases []ReleaseEntry, currentVersion, lastUpdatedFrom string) AggregatedNotes {
	normalized := make([]ReleaseEntry, 0, len(releases))
	for _, r := range releases {
		ver, tag, _, ok := ParseReleaseTag(r.Version)
		if !ok {
			ver, tag, _, ok = ParseReleaseTag(r.Tag)
		}
		if !ok {
			continue
		}
		r.Version = ver
		if r.Tag == "" {
			r.Tag = "v" + ver
		} else {
			r.Tag = tag
		}
		normalized = append(normalized, r)
	}

	slices.SortFunc(normalized, func(a, b ReleaseEntry) int {
		return CompareVersion(b.Version, a.Version)
	})

	if len(normalized) == 0 {
		return AggregatedNotes{
			FromVersion: currentVersion,
			ToVersion:   currentVersion,
		}
	}

	var newer []ReleaseEntry
	for _, r := range normalized {
		if CompareVersion(r.Version, currentVersion) > 0 {
			newer = append(newer, r)
		}
	}

	if len(newer) > 0 {
		out := AggregatedNotes{
			FromVersion:  currentVersion,
			ToVersion:    newer[0].Version,
			VersionCount: len(newer),
			HasNewer:     true,
			PublishedAt:  newer[0].PublishedAt,
			Versions:     newer,
		}
		for _, r := range newer {
			vLabel := "v" + r.Version
			mergeLocalized(&out.MergedZh, &out.TaggedZh, r.Zh, vLabel)
			mergeLocalized(&out.MergedEn, &out.TaggedEn, r.En, vLabel)
		}
		return out
	}

	if lastUpdatedFrom != "" && CompareVersion(lastUpdatedFrom, currentVersion) < 0 {
		var recent []ReleaseEntry
		for _, r := range normalized {
			if CompareVersion(r.Version, lastUpdatedFrom) > 0 && CompareVersion(r.Version, currentVersion) <= 0 {
				recent = append(recent, r)
			}
		}
		if len(recent) > 0 {
			out := AggregatedNotes{
				FromVersion:  lastUpdatedFrom,
				ToVersion:    recent[0].Version,
				VersionCount: len(recent),
				HasNewer:     false,
				PublishedAt:  recent[0].PublishedAt,
				Versions:     recent,
			}
			for _, r := range recent {
				vLabel := "v" + r.Version
				mergeLocalized(&out.MergedZh, &out.TaggedZh, r.Zh, vLabel)
				mergeLocalized(&out.MergedEn, &out.TaggedEn, r.En, vLabel)
			}
			return out
		}
	}

	picked := normalized[0]
	for _, r := range normalized {
		if CompareVersion(r.Version, currentVersion) == 0 {
			picked = r
			break
		}
	}
	out := AggregatedNotes{
		FromVersion:  currentVersion,
		ToVersion:    picked.Version,
		VersionCount: 1,
		HasNewer:     false,
		PublishedAt:  picked.PublishedAt,
		Versions:     []ReleaseEntry{picked},
	}
	vLabel := "v" + picked.Version
	mergeLocalized(&out.MergedZh, &out.TaggedZh, picked.Zh, vLabel)
	mergeLocalized(&out.MergedEn, &out.TaggedEn, picked.En, vLabel)
	return out
}
