import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const bareExtRe = /^[a-z0-9][a-z0-9_+-]{0,31}$/;
const mimeTypeRe = /^[a-z0-9][a-z0-9.+-]{0,63}\/[a-z0-9][a-z0-9.+-]{0,63}$/;

let cached = null;

function cleanHostGoEnv(root) {
  const env = { ...process.env, CGO_ENABLED: "0" };
  for (const key of [
    "GOOS",
    "GOARCH",
    "GOARM",
    "GOAMD64",
    "GO386",
    "GOMIPS",
    "GOMIPS64",
    "GOPPC64",
    "GORISCV64",
    "GOWASM",
  ]) {
    delete env[key];
  }
  const hostPair = execFileSync("go", ["env", "GOHOSTOS", "GOHOSTARCH"], {
    cwd: root,
    encoding: "utf8",
    env,
  })
    .trim()
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
  if (hostPair.length >= 2) {
    env.GOOS = hostPair[0];
    env.GOARCH = hostPair[1];
  }
  return env;
}

function validateStringList(value, label, pattern) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error(`block-fileassoc returned invalid ${label}`);
  }
  const out = [];
  const seen = new Set();
  for (const item of value) {
    if (typeof item !== "string" || item.trim() === "" || /[\r\n;]/.test(item)) {
      throw new Error(`block-fileassoc returned malformed entry in ${label}: ${JSON.stringify(item)}`);
    }
    const clean = item.trim();
    if (pattern && !pattern.test(clean)) {
      throw new Error(`block-fileassoc returned unsafe entry in ${label}: ${JSON.stringify(clean)}`);
    }
    if (!seen.has(clean)) {
      seen.add(clean);
      out.push(clean);
    }
  }
  return out;
}

export function loadFileAssociations(root = repoRoot) {
  if (cached && root === repoRoot) return cached;
  const raw = execFileSync("go", ["run", "./cmd/block-fileassoc"], {
    cwd: root,
    encoding: "utf8",
    env: cleanHostGoEnv(root),
    maxBuffer: 16 * 1024 * 1024,
  });
  const parsed = JSON.parse(raw);
  const result = {
    markdownExtensions: validateStringList(parsed.markdown_extensions, "markdown_extensions", bareExtRe),
    documentExtensions: validateStringList(parsed.document_extensions, "document_extensions", bareExtRe),
    linuxMimeTypes: validateStringList(parsed.linux_mime_types, "linux_mime_types", mimeTypeRe),
  };
  if (root === repoRoot) cached = result;
  return result;
}

export function linuxMimeTypeLine(root = repoRoot) {
  const { linuxMimeTypes } = loadFileAssociations(root);
  return `MimeType=${linuxMimeTypes.join(";")};`;
}

export function windowsExtensions(root = repoRoot) {
  const { markdownExtensions, documentExtensions } = loadFileAssociations(root);
  const combined = new Set([...markdownExtensions, ...documentExtensions]);
  return [...combined].sort().map((ext) => `.${ext}`);
}

export function renderWindowsNsisFileAssociations(root = repoRoot) {
  const exts = windowsExtensions(root);
  // Machine-wide NSIS installs use a dedicated ProgID (Block.Machine.Document)
  // so per-user or portable runs under HKCU can never shadow or break the
  // machine-wide install via HKCR merged-view precedence.
  const lines = [
    "; Auto-generated by scripts/file-associations.mjs from cmd/block-fileassoc.",
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document" "" "Block Document"',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document" "FriendlyTypeName" "Block Document"',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document\\DefaultIcon" "" \'"$INSTDIR\\block.exe",0\'',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document\\Application" "ApplicationName" "Block"',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document\\Application" "ApplicationDescription" "Block"',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document\\shell\\open" "FriendlyAppName" "Block"',
    'WriteRegStr HKLM "Software\\Classes\\Block.Machine.Document\\shell\\open\\command" "" \'"$INSTDIR\\block.exe" "%1"\'',
  ];
  for (const ext of exts) {
    lines.push(`WriteRegStr HKLM "Software\\Classes\\${ext}\\OpenWithProgids" "Block.Machine.Document" ""`);
  }
  lines.push("System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'");
  lines.push("");
  return lines.join("\n");
}

function encodeDesktopExecToken(execPath) {
  const reserved = /[ \t\n"'\\><~|&;$*?#()`]/;
  let quoted = execPath;
  if (execPath === "" || reserved.test(execPath)) {
    let out = '"';
    for (let i = 0; i < execPath.length; i += 1) {
      const c = execPath[i];
      if (c === '"' || c === "`" || c === "$" || c === "\\") {
        out += "\\";
      }
      out += c;
    }
    out += '"';
    quoted = out;
  }
  return quoted.replaceAll("\\", "\\\\");
}

export function buildLinuxDesktopExecLine(execPath) {
  if (/[\r\n\0]/.test(execPath)) {
    throw new Error(`Unsupported control character in Linux desktop Exec path: ${JSON.stringify(execPath)}`);
  }
  let encoded = encodeDesktopExecToken(execPath);
  if (execPath.includes("%")) {
    encoded = encoded.replaceAll("%", "%%");
    const shCmd = encodeDesktopExecToken('target=$1; shift; exec "$target" "$@"');
    return `/bin/sh -c ${shCmd} _ ${encoded} %F`;
  }
  return `${encoded} %F`;
}

export function installLinuxDesktopProtected({
  execPath,
  dataHome,
  configHome,
  appDataDir,
  dataDirs = process.env.XDG_DATA_DIRS || "",
  configDirs = process.env.XDG_CONFIG_DIRS || "",
  currentDesktop = process.env.XDG_CURRENT_DESKTOP || "",
  root = repoRoot,
}) {
  const args = [
    "run",
    "./cmd/block-fileassoc",
    "--install-linux-desktop",
    "--exec",
    execPath,
    "--data-home",
    dataHome,
    "--config-home",
    configHome,
    "--app-data",
    appDataDir,
  ];
  if (dataDirs) {
    args.push("--data-dirs", dataDirs);
  }
  if (configDirs) {
    args.push("--config-dirs", configDirs);
  }
  if (currentDesktop) {
    args.push("--current-desktop", currentDesktop);
  }
  execFileSync("go", args, {
    cwd: root,
    encoding: "utf8",
    env: cleanHostGoEnv(root),
    maxBuffer: 16 * 1024 * 1024,
  });
}
