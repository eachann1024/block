use gpui::{App, KeyBinding};

use super::view::{
    Annotate, CopyMarkdown, ExportImage, Backspace, Bold, Cancel, CmdEnter, Code, Copy, Cut, Delete, DeleteLineLeft, DeleteLineRight,
    DeleteWordLeft, DeleteWordRight, DocEnd, DocStart, Down, DuplicateBlock, EditLink, Enter,
    ExitBlock, Find, Italic, Left, LineEnd, LineStart, MoveBlockDown, MoveBlockUp,
    NextCell, OpenLinkAtCaret, Paste, PreviousCell,
    Redo, Right, Save, SelectAll, SelectDocEnd, SelectDocStart, SelectDown, SelectLeft,
    SelectLineEnd, SelectLineStart, SelectRight, SelectUp, SelectWordLeft, SelectWordRight,
    SetBullet, SetCode, SetH1, SetH2, SetH3, SetNumbered, SetParagraph, SetQuote, SetTodo, Strike,
    TableMenuKey, Underline, Undo, Up, WordLeft, WordRight, ToggleHighlight, ClearFormat, ToggleFold,
    PastePlain, ZoomIn, ZoomOut, ZoomReset,
};
#[cfg(any(target_os = "macos", target_family = "wasm"))]
use super::view::{LogicalLineEnd, LogicalLineStart};

pub fn bind_keys(cx: &mut App) {
    super::ai::bind_keys(cx);
    crate::ui::app_shortcuts::bind_editor(cx, [
        KeyBinding::new("left", Left, Some("Editor")),
        KeyBinding::new("right", Right, Some("Editor")),
        KeyBinding::new("shift-left", SelectLeft, Some("Editor")),
        KeyBinding::new("shift-right", SelectRight, Some("Editor")),
        KeyBinding::new("up", Up, Some("Editor")),
        KeyBinding::new("down", Down, Some("Editor")),
        KeyBinding::new("shift-up", SelectUp, Some("Editor")),
        KeyBinding::new("shift-down", SelectDown, Some("Editor")),
        KeyBinding::new("home", LineStart, Some("Editor")),
        KeyBinding::new("end", LineEnd, Some("Editor")),
        KeyBinding::new("shift-home", SelectLineStart, Some("Editor")),
        KeyBinding::new("shift-end", SelectLineEnd, Some("Editor")),
        KeyBinding::new("alt-left", WordLeft, Some("Editor")),
        KeyBinding::new("alt-right", WordRight, Some("Editor")),
        KeyBinding::new("alt-f", WordRight, Some("Editor")),
        KeyBinding::new("alt-shift-left", SelectWordLeft, Some("Editor")),
        KeyBinding::new("alt-shift-right", SelectWordRight, Some("Editor")),
        KeyBinding::new("alt-backspace", DeleteWordLeft, Some("Editor")),
        KeyBinding::new("alt-delete", DeleteWordRight, Some("Editor")),
        KeyBinding::new("alt-d", DeleteWordRight, Some("Editor")),
        KeyBinding::new("cmd-z", Undo, Some("Editor")),
        KeyBinding::new("cmd-shift-z", Redo, Some("Editor")),
        KeyBinding::new("ctrl-y", Redo, Some("Editor")),
        KeyBinding::new("escape", Cancel, Some("Editor")),
        KeyBinding::new("cmd-s", Save, Some("Editor")),
        KeyBinding::new("enter", Enter, Some("Editor")),
        KeyBinding::new("alt-enter", OpenLinkAtCaret, Some("Editor")),
        KeyBinding::new("shift-enter", ExitBlock, Some("Editor")),
        KeyBinding::new("cmd-enter", CmdEnter, Some("Editor")),
        KeyBinding::new("tab", NextCell, Some("Editor")),
        KeyBinding::new("shift-tab", PreviousCell, Some("Editor")),
        KeyBinding::new("backspace", Backspace, Some("Editor")),
        KeyBinding::new("delete", Delete, Some("Editor")),
        KeyBinding::new("cmd-a", SelectAll, Some("Editor")),
        KeyBinding::new("cmd-c", Copy, Some("Editor")),
        KeyBinding::new("cmd-x", Cut, Some("Editor")),
        KeyBinding::new("cmd-v", Paste, Some("Editor")),
        KeyBinding::new("cmd-b", Bold, Some("Editor")),
        KeyBinding::new("cmd-i", Italic, Some("Editor")),
        KeyBinding::new("cmd-shift-s", Strike, Some("Editor")),
        KeyBinding::new("cmd-shift-x", Strike, Some("Editor")),
        KeyBinding::new("cmd-e", Code, Some("Editor")),
        KeyBinding::new("cmd-u", Underline, Some("Editor")),
        KeyBinding::new("cmd-shift-k", EditLink, Some("Editor")),
        // Without a selection or link `open_link` propagates, so ⌘K still reaches the global search.
        KeyBinding::new("cmd-k", EditLink, Some("Editor")),
        KeyBinding::new("cmd-shift-h", ToggleHighlight, Some("Editor")),
        KeyBinding::new("cmd-shift-\\", ClearFormat, Some("Editor")),
        KeyBinding::new("cmd-shift-v", PastePlain, Some("Editor")),
        KeyBinding::new("cmd-shift-7", SetNumbered, Some("Editor")),
        KeyBinding::new("cmd-shift-8", SetBullet, Some("Editor")),
        KeyBinding::new("cmd-shift-9", SetQuote, Some("Editor")),
        KeyBinding::new("cmd-alt-t", ToggleFold, Some("Editor")),
        KeyBinding::new("cmd-alt-0", SetParagraph, Some("Editor")), KeyBinding::new("ctrl-shift-0", SetParagraph, Some("Editor")),
        KeyBinding::new("cmd-alt-1", SetH1, Some("Editor")), KeyBinding::new("ctrl-shift-1", SetH1, Some("Editor")),
        KeyBinding::new("cmd-alt-2", SetH2, Some("Editor")), KeyBinding::new("ctrl-shift-2", SetH2, Some("Editor")),
        KeyBinding::new("cmd-alt-3", SetH3, Some("Editor")), KeyBinding::new("ctrl-shift-3", SetH3, Some("Editor")),
        KeyBinding::new("cmd-alt-4", SetTodo, Some("Editor")), KeyBinding::new("ctrl-shift-4", SetTodo, Some("Editor")),
        KeyBinding::new("cmd-alt-5", SetBullet, Some("Editor")), KeyBinding::new("ctrl-shift-5", SetBullet, Some("Editor")),
        KeyBinding::new("cmd-alt-6", SetNumbered, Some("Editor")), KeyBinding::new("ctrl-shift-6", SetNumbered, Some("Editor")),
        KeyBinding::new("cmd-alt-8", SetCode, Some("Editor")), KeyBinding::new("ctrl-shift-8", SetCode, Some("Editor")),
        KeyBinding::new("cmd-alt-9", SetQuote, Some("Editor")), KeyBinding::new("ctrl-shift-9", SetQuote, Some("Editor")),
        KeyBinding::new("cmd-d", DuplicateBlock, Some("Editor")),
        KeyBinding::new("alt-up", MoveBlockUp, Some("Editor")),
        KeyBinding::new("cmd-alt-up", MoveBlockUp, Some("Editor")),
        KeyBinding::new("alt-down", MoveBlockDown, Some("Editor")),
        KeyBinding::new("cmd-alt-down", MoveBlockDown, Some("Editor")),
        KeyBinding::new("shift-f10", TableMenuKey, Some("Editor")),
        KeyBinding::new("cmd-=", ZoomIn, Some("Editor")),
        KeyBinding::new("cmd-+", ZoomIn, Some("Editor")),
        KeyBinding::new("cmd-shift-=", ZoomIn, Some("Editor")),
        KeyBinding::new("cmd--", ZoomOut, Some("Editor")),
        KeyBinding::new("cmd-0", ZoomReset, Some("Editor")),
        KeyBinding::new("cmd-f", Find, Some("Editor")),
        KeyBinding::new("cmd-f", Find, None),
        KeyBinding::new("shift-cmd-e", ExportImage, Some("Editor")),
        KeyBinding::new("alt-cmd-c", CopyMarkdown, Some("Editor")),
        KeyBinding::new("alt-cmd-m", Annotate, Some("Editor")),
    ]);
    #[cfg(any(target_os = "macos", target_family = "wasm"))]
    crate::ui::app_shortcuts::bind_editor(cx, [
        KeyBinding::new("cmd-left", LineStart, Some("Editor")),
        KeyBinding::new("cmd-right", LineEnd, Some("Editor")),
        KeyBinding::new("cmd-shift-left", SelectLineStart, Some("Editor")),
        KeyBinding::new("cmd-shift-right", SelectLineEnd, Some("Editor")),
        KeyBinding::new("cmd-up", DocStart, Some("Editor")),
        KeyBinding::new("cmd-down", DocEnd, Some("Editor")),
        KeyBinding::new("cmd-shift-up", SelectDocStart, Some("Editor")),
        KeyBinding::new("cmd-shift-down", SelectDocEnd, Some("Editor")),
        KeyBinding::new("cmd-backspace", DeleteLineLeft, Some("Editor")),
        KeyBinding::new("cmd-delete", DeleteLineRight, Some("Editor")),
        KeyBinding::new("ctrl-a", LogicalLineStart, Some("Editor")),
        KeyBinding::new("ctrl-e", LogicalLineEnd, Some("Editor")),
        KeyBinding::new("ctrl-w", DeleteWordLeft, Some("Editor")),
        KeyBinding::new("ctrl-u", DeleteLineLeft, Some("Editor")),
        KeyBinding::new("ctrl-k", DeleteLineRight, Some("Editor")),
    ]);
    #[cfg(not(target_os = "macos"))]
    crate::ui::app_shortcuts::bind_editor(cx, [
        KeyBinding::new("ctrl-left", WordLeft, Some("Editor")),
        KeyBinding::new("ctrl-right", WordRight, Some("Editor")),
        KeyBinding::new("ctrl-shift-left", SelectWordLeft, Some("Editor")),
        KeyBinding::new("ctrl-shift-right", SelectWordRight, Some("Editor")),
        KeyBinding::new("ctrl-backspace", DeleteWordLeft, Some("Editor")),
        KeyBinding::new("ctrl-delete", DeleteWordRight, Some("Editor")),
        KeyBinding::new("ctrl-shift-backspace", DeleteLineLeft, Some("Editor")),
        KeyBinding::new("ctrl-shift-delete", DeleteLineRight, Some("Editor")),
        KeyBinding::new("ctrl-home", DocStart, Some("Editor")),
        KeyBinding::new("ctrl-end", DocEnd, Some("Editor")),
        KeyBinding::new("ctrl-shift-home", SelectDocStart, Some("Editor")),
        KeyBinding::new("ctrl-shift-end", SelectDocEnd, Some("Editor")),
        KeyBinding::new("ctrl-shift-e", ExportImage, Some("Editor")),
        KeyBinding::new("ctrl-alt-c", CopyMarkdown, Some("Editor")),
        KeyBinding::new("ctrl-alt-m", Annotate, Some("Editor")),
        KeyBinding::new("ctrl-z", Undo, Some("Editor")),
        KeyBinding::new("ctrl-shift-z", Redo, Some("Editor")),
        KeyBinding::new("ctrl-s", Save, Some("Editor")),
        KeyBinding::new("ctrl-enter", CmdEnter, Some("Editor")),
        KeyBinding::new("ctrl-c", Copy, Some("Editor")),
        KeyBinding::new("ctrl-x", Cut, Some("Editor")),
        KeyBinding::new("ctrl-v", Paste, Some("Editor")),
        KeyBinding::new("ctrl-b", Bold, Some("Editor")),
        KeyBinding::new("ctrl-i", Italic, Some("Editor")),
        KeyBinding::new("ctrl-d", DuplicateBlock, Some("Editor")),
        KeyBinding::new("ctrl-f", Find, Some("Editor")),
        KeyBinding::new("ctrl-f", Find, None),
        KeyBinding::new("ctrl-=", ZoomIn, Some("Editor")),
        KeyBinding::new("ctrl-+", ZoomIn, Some("Editor")),
        KeyBinding::new("ctrl-shift-=", ZoomIn, Some("Editor")),
        KeyBinding::new("ctrl--", ZoomOut, Some("Editor")),
        KeyBinding::new("ctrl-0", ZoomReset, Some("Editor")),
        KeyBinding::new("ctrl-shift-s", Strike, Some("Editor")),
        KeyBinding::new("ctrl-shift-x", Strike, Some("Editor")),
        KeyBinding::new("ctrl-shift-k", EditLink, Some("Editor")),
        KeyBinding::new("ctrl-shift-h", ToggleHighlight, Some("Editor")),
        KeyBinding::new("ctrl-shift-\\", ClearFormat, Some("Editor")),
        KeyBinding::new("ctrl-shift-v", PastePlain, Some("Editor")),
        KeyBinding::new("ctrl-alt-t", ToggleFold, Some("Editor")),
    ]);
    #[cfg(not(any(target_os = "macos", target_family = "wasm")))]
    crate::ui::app_shortcuts::bind_editor(cx, [
        KeyBinding::new("ctrl-a", SelectAll, Some("Editor")),
        KeyBinding::new("ctrl-e", Code, Some("Editor")),
        KeyBinding::new("ctrl-u", Underline, Some("Editor")),
        KeyBinding::new("ctrl-k", EditLink, Some("Editor")),
    ]);
    // macOS browsers report the Option-composed character as `event.key`, so the
    // Option shortcuts are bound to those glyphs too.
    #[cfg(target_family = "wasm")]
    crate::ui::app_shortcuts::bind_editor(cx, [
        KeyBinding::new("cmd-alt-º", SetParagraph, Some("Editor")),
        KeyBinding::new("cmd-alt-¡", SetH1, Some("Editor")),
        KeyBinding::new("cmd-alt-™", SetH2, Some("Editor")),
        KeyBinding::new("cmd-alt-£", SetH3, Some("Editor")),
        KeyBinding::new("cmd-alt-¢", SetTodo, Some("Editor")),
        KeyBinding::new("cmd-alt-∞", SetBullet, Some("Editor")),
        KeyBinding::new("cmd-alt-§", SetNumbered, Some("Editor")),
        KeyBinding::new("cmd-alt-•", SetCode, Some("Editor")),
        KeyBinding::new("cmd-alt-ª", SetQuote, Some("Editor")),
        KeyBinding::new("cmd-alt-†", ToggleFold, Some("Editor")),
        KeyBinding::new("alt-cmd-ç", CopyMarkdown, Some("Editor")),
        KeyBinding::new("alt-cmd-µ", Annotate, Some("Editor")),
        KeyBinding::new("alt-∫", WordLeft, Some("Editor")),
        KeyBinding::new("alt-ƒ", WordRight, Some("Editor")),
        KeyBinding::new("alt-∂", DeleteWordRight, Some("Editor")),
    ]);
}
