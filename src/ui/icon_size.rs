//! 图标尺寸令牌：以标题栏 18px 图标为基准分档，同一角色的图标只用一档。
//! 线稿统一按 24 画布 1.5 描边绘制，档位越小实际线越细，所以不在档位之间插值。

/// 独立图标按钮（标题栏、面板头、侧栏底栏）。
pub const CHROME: f32 = 18.;
/// 列表行前导图标（文件树、菜单、设置导航、搜索框），旁边是 14px 文字。
/// 线稿只占画布约 70%，18 档的可见高度才与 14px 中文字面齐平。
pub const ROW: f32 = 18.;
/// 行内小图标（展开箭头、关闭、状态、勾选）。
pub const INLINE: f32 = 14.;
/// 12px 文字旁的微型图标。
pub const MICRO: f32 = 12.;

/// 标题栏独立按钮框；按钮所在条更高时（如侧栏底栏 30px）按钮框跟随条高。
pub const CHROME_BOX: f32 = 26.;
